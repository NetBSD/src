static u_int
ibm4xx_460ex_pll_div(const uint8_t *tab, size_t n, uint32_t code)
{
	size_t i;

	for (i = 0; i < n; i++)
		if (tab[i] == code)
			return i + 1;
	return 0;
}

/*
 * The PLL clock in MHz. 0 if the straps don't have that configuration.
 */
u_int
ibm4xx_460ex_base_clock(uint32_t cpu_hz)
{
	uint32_t strap;
	u_int fwdva, fbdv;

	strap = mfsdr(DCR_SDR0_SDSTP0);
	if (__SHIFTOUT(strap, SDR0_SDSTP0_SEL) != 0)
		return 0;

	fwdva = ibm4xx_460ex_pll_div(ibm4xx_460ex_fwdv_code,
	    __arraycount(ibm4xx_460ex_fwdv_code),
	    __SHIFTOUT(strap, SDR0_SDSTP0_FWDVA));
	fbdv = ibm4xx_460ex_pll_div(ibm4xx_460ex_fbdv_code,
	    __arraycount(ibm4xx_460ex_fbdv_code),
	    __SHIFTOUT(strap, SDR0_SDSTP0_FBDV));
	if (fwdva == 0 || fbdv == 0)
		return 0;

	return ((cpu_hz / 100000) * fwdva / fbdv) / 10;
}

